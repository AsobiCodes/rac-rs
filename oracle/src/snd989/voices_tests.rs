fn tone(prio: i8, sample: u32, a1: u16, a2: u16) -> Tone {
    Tone { priority: prio, volume: 100, centre_note: 60, centre_fine: 0, pan: 180, map_lo: 0, map_hi: 127, bend_down: 2, bend_up: 2, adsr1: a1, adsr2: a2, flags: 0, sample }
}
/// 3 blocks, the last one with the END flag and no REPEAT flag: a one-shot of 84 samples.
fn oneshot() -> Arc<Bank> {
    let mut data = vec![0u8; 48];
    data[1] = 0x04;
    data[33] = 0x01;
    let s = Sound { volume: 100, group: 0, pan: 90, pad5: 0, flags: 0, grain_offset: 0, grains: vec![] };
    Arc::new(Bank { signature: Signature { id: 0, sounds: 1, grains: 0, vags: 0 }, sounds: vec![s], data })
}
fn req(bank: &Arc<Bank>, slot: usize, tick: u32, prio: i8) -> KeyOn {
    KeyOn { tick, slot, handle: 0x8500_0001, bank_handle: 7, bank: bank.clone(), sound: 0, grain: 0, tone: tone(prio, 0, 0x00ff, 0x1fc0), group: 0, priority: prio, tone_volume: 100, tone_pan: 0, volume: 100, pan: 0, scale: 0x400, centre: 60, centre_fine: 0, bend: 0, pitch_mod: 0, sound_flags: 0 }
}
fn key(v: &mut SpuVoices, bank: &Arc<Bank>, slot: usize, tick: u32, prio: i8) -> Option<usize> {
    v.tick_begin(tick);
    let g = v.alloc(tick, 0, prio)?;
    v.key_on(g.voice, &req(bank, slot, tick, prio));
    v.apply_key_offs(tick);
    v.apply_key_ons(tick);
    Some(g.voice)
}
fn disc_irx(name: &str) -> Option<Vec<u8>> {
    let blob = testdata::read("globals/irx.bin")?;
    Irx::find_in_blob(&blob, name).map(|b| b.to_vec())
}

