//! cutapi: the capability sandbox of the region cutter (scratch_cut/CUTTER.md 12.12).
//!
//! A worker's region module is compiled as its own crate (`cutwork`: `#![no_std]`, `#![forbid(unsafe_code)]`, no build script) that depends on THIS crate
//! only. The only value of a machine type it can ever get is `&mut Ctx`, and `Ctx` has exactly the methods below: registers and soft state, memory
//! accesses, `call` of the region's own callees, and the block marker `at`. There is no way to step, execute or dispatch retail instructions, no
//! `Cpu` field, no hook, no file, no stdout. What the checker needs from a run (the block trace) is held inside the `Ctx` (the worker cannot reach
//! it) and published by `run` after the worker function has returned; violations are reported through `Cpu::stop` ("sandbox: ..."), which the worker
//! cannot clear (no accessor).
//!
//! Everything here is trusted code (hashed by cutmanifest.py). A `Policy` is generated by the gate from the canonical cutter output, never by the worker.
#![forbid(unsafe_code)]

#[path = "../../src/ps2.rs"]
#[allow(dead_code)]
mod ps2;

pub use ps2::{F, V, W, X, XYZ, Y, Z};

use ee_oracle::cpu::Cpu;
use ps2::Ee;
use std::cell::{Cell, RefCell};

/// The exit a region returns for the function's own `jr ra` (same value as `cut::RETURN`).
pub const RETURN: u32 = u32::MAX;

/// What one Rust region may do. Generated by the gate (from cutter.py's JSON); all addresses are plain RAM addresses (< 0x2000000).
pub struct Policy {
    /// Region index in the function's table.
    pub k: u32,
    /// The function [entry, end) and the region [lo, hi).
    pub entry: u32,
    pub end: u32,
    pub lo: u32,
    pub hi: u32,
    /// The function calls itself (its own entry may then be a call target when the region's retail code calls it).
    pub recursive: bool,
    /// Call targets the region's retail code has (`jal`/`bal` in the region), as the cutter found them.
    pub calls: &'static [u32],
    /// The region has a computed call (`jalr`): any target outside the function's own code is allowed.
    pub dyn_call: bool,
    /// Ranges inside [entry, end) that hold data (the cutter's unreachable ranges): readable.
    pub data: &'static [(u32, u32)],
}

thread_local! {
    static TRACING: Cell<bool> = const { Cell::new(false) };
    static BLOCKS: RefCell<Option<Vec<u32>>> = const { RefCell::new(None) };
    static DEPTH: Cell<u32> = const { Cell::new(0) };
}

/// Checker only: record the block markers of every Rust region run on this thread (published by `run` when the outermost region ends).
pub fn set_tracing(on: bool) {
    TRACING.set(on);
}

/// Checker only: the block markers of the last outermost region run (None: the region did not run through `run`, or tracing was off).
pub fn take_blocks() -> Option<Vec<u32>> {
    BLOCKS.with_borrow_mut(|b| b.take())
}

struct Depth;

impl Depth {
    fn enter() -> Depth {
        DEPTH.set(DEPTH.get() + 1);
        Depth
    }
}

impl Drop for Depth {
    fn drop(&mut self) {
        DEPTH.set(DEPTH.get().saturating_sub(1));
    }
}

/// Runs the worker's region function `f` on the machine with the region's policy (glue only). Returns the exit pc.
pub fn run(c: &mut Cpu, p: &Policy, pc: u32, f: fn(&mut Ctx<'_>, u32) -> u32) -> u32 {
    let trace = if TRACING.get() { Some(Vec::new()) } else { None };
    let mut x = Ctx { c, p, trace };
    let g = Depth::enter();
    let exit = f(&mut x, pc);
    drop(g);
    if DEPTH.get() == 0 {
        BLOCKS.with_borrow_mut(|b| *b = x.trace.take());
    }
    exit
}

/// The machine as a Rust region sees it.
pub struct Ctx<'a> {
    c: &'a mut Cpu,
    p: &'a Policy,
    trace: Option<Vec<u32>>,
}

#[inline(always)]
fn norm(a: u32) -> u32 {
    a & 0x1fff_ffff
}

impl Ctx<'_> {
    /// Reports a violation: the CPU stops with "sandbox: ..." (the first one wins); the checker fails the visit with [sandbox].
    #[cold]
    fn viol(&mut self, what: &str, a: u32) {
        if self.c.stop.is_none() {
            self.c.stop = Some(format!("sandbox: region R{} of {:#x}: {what} {a:#x}", self.p.k, self.p.entry));
        }
    }

    /// True when [a, a+n) touches the function's own code and is not data.
    #[inline(always)]
    fn in_code(&self, a: u32, n: u32) -> bool {
        let (s, e) = (norm(a), norm(a).wrapping_add(n));
        let p = self.p;
        s < p.end && e > p.entry && !p.data.iter().any(|&(lo, hi)| s >= lo && e <= hi)
    }

    #[inline(always)]
    fn rd_ok(&mut self, a: u32, n: u32) -> bool {
        if self.in_code(a, n) {
            self.viol("read of the function's own code at", a);
            false
        } else {
            true
        }
    }

    #[inline(always)]
    fn wr_ok(&mut self, a: u32, n: u32) -> bool {
        let (s, e) = (norm(a), norm(a).wrapping_add(n));
        if s < self.p.end && e > self.p.entry {
            self.viol("write into the function's own code at", a);
            false
        } else {
            true
        }
    }

    // ---- block markers

    /// Marks the start of the retail basic block that begins at `pc` (a literal; the lint checks it is a block leader of this region and that
    /// each leader is marked once). The checker compares the sequence of marks with the retail run's sequence of block entries.
    #[inline(always)]
    pub fn at(&mut self, pc: u32) {
        if let Some(t) = self.trace.as_mut() {
            t.push(pc);
        }
    }

    // ---- general registers

    /// Low 64 bits of GPR `i`.
    #[inline(always)]
    pub fn g(&self, i: usize) -> u64 {
        self.c.g(i)
    }
    /// Sets the low 64 bits of GPR `i` (the upper half is kept; $zero ignores it).
    #[inline(always)]
    pub fn s(&mut self, i: usize, v: u64) {
        self.c.s(i, v)
    }
    /// All 128 bits of GPR `i`.
    #[inline(always)]
    pub fn r(&self, i: usize) -> u128 {
        self.c.r[i]
    }
    /// Sets all 128 bits of GPR `i` ($zero ignores it).
    #[inline(always)]
    pub fn set_r(&mut self, i: usize, v: u128) {
        if i != 0 {
            self.c.r[i] = v;
        }
    }
    #[inline(always)]
    pub fn hi(&self) -> u128 {
        self.c.hi
    }
    #[inline(always)]
    pub fn lo(&self) -> u128 {
        self.c.lo
    }
    #[inline(always)]
    pub fn set_hi(&mut self, v: u128) {
        self.c.hi = v;
    }
    #[inline(always)]
    pub fn set_lo(&mut self, v: u128) {
        self.c.lo = v;
    }
    #[inline(always)]
    pub fn sa(&self) -> u32 {
        self.c.sa
    }
    #[inline(always)]
    pub fn set_sa(&mut self, v: u32) {
        self.c.sa = v;
    }

    // ---- FPU (COP1)

    /// Bits of FPR `i`.
    #[inline(always)]
    pub fn f(&self, i: usize) -> u32 {
        self.c.f[i]
    }
    #[inline(always)]
    pub fn set_f(&mut self, i: usize, bits: u32) {
        self.c.f[i] = bits;
    }
    #[inline(always)]
    pub fn facc(&self) -> u32 {
        self.c.facc
    }
    #[inline(always)]
    pub fn set_facc(&mut self, v: u32) {
        self.c.facc = v;
    }
    #[inline(always)]
    pub fn fcr31(&self) -> u32 {
        self.c.fcr31
    }
    #[inline(always)]
    pub fn set_fcr31(&mut self, v: u32) {
        self.c.fcr31 = v;
    }

    // ---- VU0 (COP2) macro-mode state

    #[inline(always)]
    pub fn vf(&self, n: usize) -> V {
        self.c.vf(n)
    }
    #[inline(always)]
    pub fn set_vf(&mut self, n: usize, v: V) {
        self.c.set_vf(n, v)
    }
    #[inline(always)]
    pub fn acc(&self) -> V {
        self.c.acc()
    }
    #[inline(always)]
    pub fn set_acc(&mut self, v: V) {
        self.c.set_acc(v)
    }
    /// VU0 integer / control register `i` (vi0..vi15, status / MAC / clip / R / I / Q at 16..22).
    #[inline(always)]
    pub fn vi(&self, i: usize) -> u32 {
        self.c.vi[i]
    }
    #[inline(always)]
    pub fn set_vi(&mut self, i: usize, v: u32) {
        self.c.vi[i] = v;
    }

    // ---- calling convention helpers

    #[inline(always)]
    pub fn arg(&self, i: usize) -> u32 {
        self.c.arg(i)
    }
    #[inline(always)]
    pub fn farg(&self, i: usize) -> F {
        self.c.farg(i)
    }
    #[inline(always)]
    pub fn set_arg(&mut self, i: usize, v: u32) {
        self.c.set_arg(i, v)
    }
    #[inline(always)]
    pub fn set_farg(&mut self, i: usize, f: F) {
        self.c.set_farg(i, f)
    }
    #[inline(always)]
    pub fn result(&self) -> u32 {
        self.c.result()
    }
    #[inline(always)]
    pub fn fresult(&self) -> F {
        self.c.fresult()
    }
    /// v0 = `v` (sign-extended).
    #[inline(always)]
    pub fn ret(&mut self, v: u32) {
        self.c.ret(v)
    }
    /// f0 = `f`.
    #[inline(always)]
    pub fn fret(&mut self, f: F) {
        self.c.fret(f)
    }

    // ---- memory (side effects of hardware registers included, as a retail load/store has them)

    #[inline(always)]
    pub fn r8(&mut self, a: u32) -> u8 {
        if self.rd_ok(a, 1) { self.c.mem.rd8(a) } else { 0 }
    }
    #[inline(always)]
    pub fn r16(&mut self, a: u32) -> u16 {
        if self.rd_ok(a, 2) { self.c.mem.rd16(a) } else { 0 }
    }
    #[inline(always)]
    pub fn r32(&mut self, a: u32) -> u32 {
        if self.rd_ok(a, 4) { self.c.mem.rd32(a) } else { 0 }
    }
    #[inline(always)]
    pub fn r64(&mut self, a: u32) -> u64 {
        if self.rd_ok(a, 8) { self.c.mem.rd64(a) } else { 0 }
    }
    #[inline(always)]
    pub fn r128(&mut self, a: u32) -> u128 {
        if self.rd_ok(a & !15, 16) { self.c.mem.rd128(a) } else { 0 }
    }
    #[inline(always)]
    pub fn rf(&mut self, a: u32) -> F {
        F(self.r32(a))
    }
    #[inline(always)]
    pub fn rv(&mut self, a: u32) -> V {
        if self.rd_ok(a & !15, 16) { self.c.rv(a) } else { V([0; 4]) }
    }
    #[inline(always)]
    pub fn w8(&mut self, a: u32, v: u8) {
        if self.wr_ok(a, 1) {
            self.c.mem.wr8(a, v)
        }
    }
    #[inline(always)]
    pub fn w16(&mut self, a: u32, v: u16) {
        if self.wr_ok(a, 2) {
            self.c.mem.wr16(a, v)
        }
    }
    #[inline(always)]
    pub fn w32(&mut self, a: u32, v: u32) {
        if self.wr_ok(a, 4) {
            self.c.mem.wr32(a, v)
        }
    }
    #[inline(always)]
    pub fn w64(&mut self, a: u32, v: u64) {
        if self.wr_ok(a, 8) {
            self.c.mem.wr64(a, v)
        }
    }
    #[inline(always)]
    pub fn w128(&mut self, a: u32, v: u128) {
        if self.wr_ok(a & !15, 16) {
            self.c.mem.wr128(a, v)
        }
    }
    #[inline(always)]
    pub fn wf(&mut self, a: u32, f: F) {
        self.w32(a, f.0)
    }
    #[inline(always)]
    pub fn wv(&mut self, a: u32, v: V) {
        if self.wr_ok(a & !15, 16) {
            self.c.wv(a, v)
        }
    }

    // ---- calls to the region's retail callees

    /// A call is allowed to a target the region's retail code calls (`Policy::calls`), or to any target outside the function's own code when the
    /// region has a computed call. Never to the function's own code (that would be hidden retail), except its own entry of a recursive function whose region calls it.
    fn call_ok(&mut self, addr: u32) -> bool {
        let n = norm(addr);
        let p = self.p;
        let own = n >= p.entry && n < p.end;
        let ok = (!own || (p.recursive && n == p.entry)) && (p.dyn_call || p.calls.contains(&n));
        if !ok {
            self.viol("call of a target that is not one of the region's callees:", addr);
        }
        ok
    }

    /// Calls the retail function at `addr` with integer / float arguments and returns (v0, f0); every general and float register is put back
    /// afterwards (`h::call`).
    pub fn call(&mut self, addr: u32, ints: &[u32], floats: &[F]) -> (u32, F) {
        if !self.call_ok(addr) {
            return (0, F(0));
        }
        let (r, f) = (self.c.r, self.c.f);
        for (i, &a) in ints.iter().enumerate() {
            self.c.set_arg(i, a);
        }
        for (i, &x) in floats.iter().enumerate() {
            self.c.set_farg(i, x);
        }
        self.c.call(addr);
        let ret = (self.c.result(), self.c.fresult());
        self.c.r = r;
        self.c.f = f;
        ret
    }

    /// Like `call`, but keeps what a retail callee leaves by the ABI-visible convention: only s0-s7, gp, sp, fp, ra and f20-f31 are put back, the
    /// scratch registers stay as the callee left them, as after a retail `jal` (`h::call_keep`).
    pub fn call_keep(&mut self, addr: u32, ints: &[u32], floats: &[F]) -> (u32, F) {
        if !self.call_ok(addr) {
            return (0, F(0));
        }
        let (r, f) = (self.c.r, self.c.f);
        for (i, &a) in ints.iter().enumerate() {
            self.c.set_arg(i, a);
        }
        for (i, &x) in floats.iter().enumerate() {
            self.c.set_farg(i, x);
        }
        self.c.call(addr);
        for i in (16..24).chain(28..32) {
            self.c.r[i] = r[i];
        }
        for i in 20..32 {
            self.c.f[i] = f[i];
        }
        (self.c.result(), self.c.fresult())
    }
}
