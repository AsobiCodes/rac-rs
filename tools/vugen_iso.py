ORB_HEAD = """//! PAR-2a nanotech orb mesh tables (FUN_002d91b8): exact f32 bit patterns of the body positions and ST, the rim
//! and glass corner vertices and their index quads (decomp/notes/particles.md PAR-2a).
"""




def u32(b, o):
    return struct.unpack_from('<I', b, o)[0]


class IsoDisc:
    def __init__(self, path):
        self.f = open(path, 'rb')

    def bytes(self, lba, n):
        self.f.seek(lba * ISO_SEC)
        return self.f.read(n)


BOOT_NAMES = {'SCES_509.16': 0, 'SCUS_971.99': 0xc0}   # boot ELF -> shift of the orb tables in the Veldin overlay section
ORB_SHIFT = 0


def boot_elf(d):
    """SCES_509.16 (PAL) or SCUS_971.99 (USA) via a minimal ISO9660 walk (root directory record); sets ORB_SHIFT."""
    global ORB_SHIFT
    pvd = d.bytes(16, ISO_SEC)
    assert pvd[1:6] == b'CD001', 'not an ISO9660 image'
    root_lba, root_len = u32(pvd, 156 + 2), u32(pvd, 156 + 10)
    dirdata = d.bytes(root_lba, root_len)
    o = 0
    while o < len(dirdata):
        ln = dirdata[o]
        if ln == 0:
            o = (o // ISO_SEC + 1) * ISO_SEC
            continue
        name = dirdata[o + 33:o + 33 + dirdata[o + 32]].decode('latin1')
        for bn, shift in BOOT_NAMES.items():
            if name.upper().startswith(bn):
                ORB_SHIFT = shift
                return d.bytes(u32(dirdata, o + 2), u32(dirdata, o + 10))
        o += ln
    raise FileNotFoundError('neither SCES_509.16 nor SCUS_971.99 on the disc image')


def wad_decompress(data):
    """Insomniac WAD LZ (port of rac-rs/src/wad.rs)."""
    assert data[:3] == b'WAD'
    end = min(u32(data, 3), len(data))
    out = bytearray()
    src = 16
    last = 0xff
    if src < end and data[src] > 0x11:
        n = data[src] - 0x11
        out += data[src + 1:src + 1 + n]
        src += 1 + n
        last = 0
    while src < end:
        flag = data[src]
        if flag < 0x10:
            if last < 0x10:
                raise ValueError('double literal')
            if flag == 0:
                ln, st = data[src + 1] + 18, src + 2
            else:
                ln, st = flag + 3, src + 1
            out += data[st:st + ln]
            src = st + ln
        else:
            if flag >= 0x40:
                b = data[src + 1]
                cl = (flag >> 5) + 1
                dist = b * 8 + ((flag >> 2) & 7) + 1
                tail = flag & 3
                nxt = src + 2
            elif flag >= 0x20:
                if flag == 0x20:
                    cl, p = data[src + 1] + 33, src + 2
                else:
                    cl, p = (flag & 0x1f) + 2, src + 1
                an, b = data[p], data[p + 1]
                dist = (an >> 2) + b * 0x40 + 1
                tail = an & 3
                nxt = p + 2
            else:
                a = (flag >> 3) & 1
                m3 = flag & 7
                if m3 == 0:
                    cl, p = data[src + 1] + 9, src + 2
                else:
                    cl, p = m3 + 2, src + 1
                bn, c = data[p], data[p + 1]
                b = bn >> 2
                tail = bn & 3
                nxt = p + 2
                if a == 0 and b == 0 and c == 0:
                    if m3 != 1:
                        s = nxt
                        while s < end and (s % 0x2000) != 0x10:
                            s += 1
                        src = s
                        last = flag
                        continue
                    cl = 0
                    dist = 0
                else:
                    dist = 0x4000 + a * 0x4000 + b + c * 0x40
            if cl > 0:
                if dist > len(out):
                    raise ValueError('bad offset')
                frm = len(out) - dist
                for i in range(cl):
                    out.append(out[frm + i])
            out += data[nxt:nxt + tail]
            src = nxt + tail
        last = flag
    return bytes(out)


def level_section(d, lvl, idx):
    """Section idx of level lvl's asset (TOC at LBA 1500, header, section table), WAD-decompressed when packed."""
    toc = d.bytes(1500, 0x2960)
    assert u32(toc, 0) == 1 and u32(toc, 4) == 0x2960, 'unexpected disc TOC'
    hdr = d.bytes(u32(toc, 0x28c8 + lvl * 8), 0x2434)
    assert u32(hdr, 0) == lvl and u32(hdr, 4) == 0x2434, 'unexpected level header'
    data = d.bytes(u32(hdr, 8), u32(hdr, 12) * ISO_SEC)
    off, size = u32(data, idx * 8), u32(data, idx * 8 + 4)
    raw = data[off:off + size]
    return wad_decompress(raw) if raw[:3] == b'WAD' else raw


def orb_rs(d):
    """Text of rac-rs/src/particles/orb_tables.rs, built from the Veldin overlay on the disc."""
    ov = level_section(d, 0, 0)
    out = [ORB_HEAD]
    for name, ty, w, n, size, off, want, doc in ORB_TABLES:
        b = ov[off + ORB_SHIFT:off + ORB_SHIFT + size]
        h = hashlib.sha256(b).hexdigest()
        if h != want:
            sys.exit('%s: orb table does not match the PAL v1.00 disc (sha256 %s)' % (name, h))
        fmt = '<%d%s' % (len(b) // (4 if ty == 'u32' else 2), 'I' if ty == 'u32' else 'h')
        vals = struct.unpack(fmt, b)
        rows = []
        for r in range(n):
            v = vals[r * w:(r + 1) * w]
            rows.append('\t[' + ', '.join(('0x%08x' % x) if ty == 'u32' else str(x) for x in v) + '],')
        out.append('/// %s\npub const %s: [[%s; %d]; %d] = [\n%s\n];\n' % (doc, name, ty, w, n, '\n'.join(rows)))
    return '\n'.join(out)


# skinned_vertex_stream's one-joint vertex loop (+0x694 .. +0x92c of the function, 166 words): first word and FNV-1a 64 over
# the words. Same match as recgen_iso.py's SKIN_FF; PAL and USA hold the same words (the function is in every level overlay).
SKIN_LOOP = (0x784b0000, 166, 0xe0a6afc1c2f6f8db)
SKIN_LOOP_OFF = 0x694


def skin_loop_words(d):
    """The 166 loop words as bytes, from the first level overlay of the disc that holds them (Veldin's does)."""
    first, n, want = SKIN_LOOP
    for lvl in range(19):
        ov = level_section(d, lvl, 0)
        w = struct.unpack('<%dI' % (len(ov) // 4), ov[:len(ov) // 4 * 4])
        for i, x in enumerate(w):
            if x != first or i + n > len(w):
                continue
            h = 0xcbf29ce484222325
            for y in w[i:i + n]:
                h = ((h ^ y) * 0x100000001b3) & 0xffffffffffffffff
            if h == want:
                return ov[i * 4:(i + n) * 4]
    sys.exit('skinning fast path: the one-joint vertex loop of skinned_vertex_stream was not found in any level overlay of this disc')


def cut(elf, n):
    size, offs, _ = PROGS[n] if n in PROGS else VU0_EXTRA[n]
    out = bytearray(size)
    for i, o in enumerate(offs):
        lo = i * CHUNK
        ln = min(CHUNK, size - lo)
        out[lo:lo + ln] = elf[o:o + ln]
    return bytes(out)


def vu0_stub(name):
    """vu0_<name>.rs for a disc whose copy of the program is not the known one: no native code (the interpreter runs it)."""
    up = name.upper()
    base = '/// Micro address of the first byte of %s.\npub const BASE: usize = %#x;\n\n' % (up, VU0_BASE[name]) if VU0_BASE[name] else ''
    return ('''//! @generated by tools/vugen_iso.py: this disc's %s is not the PAL v1.00 one, so the interpreter runs it. Do not edit.
#![allow(dead_code, clippy::all)]
use crate::cpu::Cpu;

pub const NODES: usize = 0;

%s/// Empty: never matches micro memory (`vu0_aot_check`).
pub static %s: [u8; 0] = [];

pub fn entry_node(_pc: usize) -> Option<u32> {
    None
}

pub fn park_reg(_pc: usize) -> Option<usize> {
    None
}

impl Cpu {
    pub(crate) fn vu0_%s_run<const COV: bool>(&mut self, _n: u32) -> Result<(u64, u64, usize, bool), String> {
        Err("vu0_%s: no native code".into())
    }
}
''' % (name, base, up, name, name))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--iso', required=True)
    ap.add_argument('--out', help='write vu0_prog0.rs and the VU1 files into this one folder')
    ap.add_argument('--tree', default=os.path.join(HERE, '..'), help='source tree root (default: the folder above tools/)')
    ap.add_argument('--keep-bins', action='store_true')
    a = ap.parse_args()
    final = None
    if a.out:
        out0 = out1 = os.path.abspath(a.out)
        bins = os.path.join(out1, 'bins')
    else:
        # Everything is made in a staging folder first and then copied into the source tree only where the content differs:
        # a regenerate of an up-to-date install leaves the files (and their mtime) alone, so cargo rebuilds nothing.
        tree = os.path.abspath(a.tree)
        final = (os.path.join(tree, 'oracle', 'src'), os.path.join(tree, 'rac-rs', 'src', 'gsfull'), os.path.join(tree, 'rac-rs', 'src', 'particles'))
        for d in final:
            os.makedirs(d, exist_ok=True)
        out0 = out1 = os.path.join(tree, 'generated', 'vu_stage')
        shutil.rmtree(out1, ignore_errors=True)
        bins = os.path.join(out1, 'bins')
    os.makedirs(bins, exist_ok=True)
    disc = IsoDisc(a.iso)
    elf = boot_elf(disc)
    sys.path.insert(0, os.path.join(HERE, 'vu'))
    import vu_disasm
    for n in sorted(PROGS):
        b = cut(elf, n)
        want = PROGS[n][2]
        h = hashlib.sha256(b).hexdigest()
        if want is not None and h != want:
            sys.exit('prog%d: microcode does not match the PAL v1.00 boot code (sha256 %s)' % (n, h))
        with open(os.path.join(bins, 'prog%d.bin' % n), 'wb') as f:
            f.write(b)
    txt = vu_disasm.render(open(os.path.join(bins, 'prog0.bin'), 'rb').read(), 0)[0]
    with open(os.path.join(bins, 'prog0.s'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(txt)
    vu0_known = []
    for name in VU0_EXTRA:
        b = cut(elf, name)
        if hashlib.sha256(b).hexdigest() != VU0_EXTRA[name][2]:
            print('vu: %s differs from the PAL v1.00 microcode, it stays in the interpreter' % name)
            with open(os.path.join(out0, 'vu0_%s.rs' % name), 'w', encoding='utf-8', newline='\n') as f:
                f.write(vu0_stub(name))
            continue
        vu0_known.append(name)
        with open(os.path.join(bins, name + '.bin'), 'wb') as f:
            f.write(b)
        with open(os.path.join(bins, name + '.s'), 'w', encoding='utf-8', newline='\n') as f:
            f.write(vu_disasm.render(b, VU0_BASE[name])[0])
    orbdir = out1
    with open(os.path.join(orbdir, 'orb_tables.rs'), 'w', encoding='ascii', newline='\n') as f:
        f.write(orb_rs(disc))
    env = dict(os.environ, VU_BINS=bins)
    vu = os.path.join(HERE, 'vu')
    r = subprocess.run([sys.executable, os.path.join(vu, 'vu0gen.py'), os.path.join(out0, 'vu0_prog0.rs')], cwd=vu, env=env)
    if r.returncode:
        sys.exit('vu0gen.py failed')
    for name in vu0_known:
        r = subprocess.run([sys.executable, os.path.join(vu, 'vu0gen.py'), os.path.join(out0, 'vu0_%s.rs' % name)], cwd=vu,
                           env=dict(env, VU0_PROG=name))
        if r.returncode:
            sys.exit('vu0gen.py failed (%s)' % name)
    r = subprocess.run([sys.executable, os.path.join(vu, 'vu1gen.py'), '--bins', bins, '--out', out1,
                        '--profile', os.path.join(vu, 'profile.txt')], cwd=vu, env=env)
    if r.returncode:
        sys.exit('vu1gen.py failed')
    # skinning fast path: EE half from the loop's code words on the disc, VU half from the prog0 translation just made
    blob = bytearray(SKIN_LOOP_OFF + 4 * SKIN_LOOP[1])
    blob[SKIN_LOOP_OFF:] = skin_loop_words(disc)
    with open(os.path.join(bins, 'skinff_loop.bin'), 'wb') as f:
        f.write(blob)
    r = subprocess.run([sys.executable, os.path.join(HERE, 'skinff_ee.py'), os.path.join(bins, 'skinff_loop.bin'), '0',
                        os.path.join(out0, 'skinff_ee.rs')])
    if r.returncode:
        sys.exit('skinff_ee.py failed')
    r = subprocess.run([sys.executable, os.path.join(HERE, 'skinff_gen.py'), os.path.join(out0, 'vu0_prog0.rs'),
                        os.path.join(out0, 'skinff_vu.rs')])
    if r.returncode:
        sys.exit('skinff_gen.py failed')
    if not a.keep_bins:
        for f in os.listdir(bins):
            os.remove(os.path.join(bins, f))
        os.rmdir(bins)
    if final:
        made = [f for f in os.listdir(out1) if os.path.isfile(os.path.join(out1, f))]
        changed = 0
        for f in made:
            dst = os.path.join(final[0] if f.startswith(('vu0_prog', 'skinff_')) else final[2] if f == 'orb_tables.rs' else final[1], f)
            new = open(os.path.join(out1, f), 'rb').read()
            try:
                same = open(dst, 'rb').read() == new
            except OSError:
                same = False
            if not same:
                open(dst, 'wb').write(new)
                changed += 1
        for f in os.listdir(final[1]):          # VU1 programs an older run made and this one does not
            if f.startswith('vu1_prog') and f.endswith('.rs') and f not in made:
                os.remove(os.path.join(final[1], f))
                changed += 1
        if not a.keep_bins:
            shutil.rmtree(out1, ignore_errors=True)
        print('vu: %d of %d generated files differed and were written' % (changed, len(made)))
        out0, out1, orbdir = final
    print('vu: generated vu0_prog0.rs, vu0_prog1.rs, vu0_prog9hi.rs, skinff_ee.rs, skinff_vu.rs in', out0, '+ 9 VU1 programs in', out1, '+ orb_tables.rs in', orbdir)


if __name__ == '__main__':
    main()
