fn strokes(c: char) -> Vec<(bool, Vec<P>)> {
	let Some((_, def)) = GLYPHS.iter().find(|g| g.0 == c) else {
		return Vec::new();
	};
	def.split('|')
		.map(|s| {
			let smooth = s.starts_with('s');
			let pts = s
				.trim_start_matches('s')
				.split(' ')
				.map(|p| {
					let (x, y) = p.split_once(',').unwrap();
					(x.parse().unwrap(), y.parse().unwrap())
				})
				.collect();
			(smooth, pts)
		})
		.collect()
}

fn advance(c: char) -> f32 {
	let w = strokes(c).iter().flat_map(|s| s.1.iter()).fold(0.0f32, |m, p| m.max(p.0));
	if c == ' ' { 0.45 } else { w + 0.28 }
}

/// The width the string takes at `height`.
pub fn width(s: &str, height: f32) -> f32 {
	s.chars().map(advance).sum::<f32>() * height
}

/// Writes `s` with its top-left at (`x`, `y`) and capitals `height` high. Every letter has its own marker colour from `palette`
/// (cycled), baseline, tilt and size. Returns the text written, so the scene can record it.
pub fn text(h: &mut Hand, s: &str, x: f32, y: f32, height: f32, palette: &[[f32; 3]]) -> String {
	let mut cx = x;
	let mut k = 0;
	for ch in s.chars() {
		let adv = advance(ch) * height;
		if ch != ' ' {
			let size = h.rng.range(0.92, 1.08);
			let tilt = h.rng.range(-0.12, 0.12);
			let dy = h.rng.range(-0.06, 0.06) * height;
			let col = palette[k % palette.len()];
			k += 1;
			let pen = Pen::ink(col).width((height * 0.11).clamp(4.0, 12.0)).wobble((height * 0.035).max(2.0));
			let (ct, st) = (cos(tilt), sin(tilt));
			let (ox, oy) = (cx, y + dy);
			let m = |p: P| -> P {
				let (px, py) = ((p.0 - 0.3) * height * size, (p.1 - 0.5) * height * size);
				(ox + 0.3 * height + px * ct - py * st, oy + 0.5 * height + px * st + py * ct)
			};
			for (smooth, pts) in strokes(ch) {
				let mp: Vec<P> = pts.iter().map(|p| m(*p)).collect();
				if smooth {
					h.curve(&mp, &pen);
				} else if pts.len() == 2 && (pts[0].1 - pts[1].1).abs() < 0.08 && (pts[0].0 - pts[1].0).abs() < 0.08 {
					h.dot(mp[0], pen.w * 0.7, &pen);
				} else {
					h.path(&mp, &pen);
				}
			}
		}
		cx += adv;
	}
	s.to_string()
}
