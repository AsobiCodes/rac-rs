//! Keeps new giant files and functions out (user, 2026-10-22: "how do we make sure we never have 5k lines monoliths again").
//! Every hand-written .rs file of rac-rs (src, exe/src) and of the oracle runtime beside it (oracle/src, oracle/core/src,
//! oracle/game/src) stays within FILE_MAX lines and every fn within FN_MAX lines (its `fn` line to its closing brace). The ones
//! that were bigger on 2026-10-22 have a cap in SIZE_CAPS.txt (next to Cargo.toml), their size that day. A cap only goes down:
//! growing past it fails, and so does shrinking under it until `RAC_SIZE_CAPS_WRITE=1 cargo test --lib size_limits` lowers it
//! (it lowers caps and drops the ones back within the limit; it never raises or adds one, except that it writes the whole list
//! when SIZE_CAPS.txt is missing). Machine-written files ("generated by" or "@generated" in the first 5 lines) are exempt.
//! A pure move of a capped file or fn: change its path in SIZE_CAPS.txt by hand (tools\movecheck.py proves the move). Raising
//! a cap or adding a line by hand fails too: the file is compared with its committed version (git HEAD).
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

const FILE_MAX: usize = 1500;
const FN_MAX: usize = 150;

/// The scanned source folders, relative to the project folder (rac-rs's parent); one that is not there (a lane without an
/// oracle copy) is skipped, and so are its caps.
const DIRS: [&str; 5] = ["rac-rs/src", "rac-rs/exe/src", "oracle/src", "oracle/core/src", "oracle/game/src"];

fn root() -> PathBuf {
	Path::new(env!("CARGO_MANIFEST_DIR")).parent().expect("rac-rs has a parent folder").to_path_buf()
}

fn caps_path() -> PathBuf {
	Path::new(env!("CARGO_MANIFEST_DIR")).join("SIZE_CAPS.txt")
}

fn ident(c: char) -> bool {
	c.is_alphanumeric() || c == '_'
}

/// The text with comments, string and char literals blanked (newlines kept), so braces and `fn` are only code.
fn code_only(src: &str) -> Vec<char> {
	let c: Vec<char> = src.chars().collect();
	let mut out = c.clone();
	let blank = |out: &mut Vec<char>, a: usize, b: usize| {
		for x in out.iter_mut().take(b).skip(a) {
			if *x != '\n' {
				*x = ' ';
			}
		}
	};
	let mut i = 0;
	while i < c.len() {
		let (ch, next) = (c[i], c.get(i + 1).copied());
		let raw_prefix = i == 0 || !ident(c[i - 1]) || (matches!(c[i - 1], 'b' | 'c') && (i < 2 || !ident(c[i - 2])));
		if ch == '/' && next == Some('/') {
			let e = c[i..].iter().position(|&x| x == '\n').map_or(c.len(), |p| i + p);
			blank(&mut out, i, e);
			i = e;
		} else if ch == '/' && next == Some('*') {
			let (mut depth, mut j) = (1, i + 2);
			while j < c.len() && depth > 0 {
				if c[j] == '/' && c.get(j + 1) == Some(&'*') {
					depth += 1;
					j += 2;
				} else if c[j] == '*' && c.get(j + 1) == Some(&'/') {
					depth -= 1;
					j += 2;
				} else {
					j += 1;
				}
			}
			blank(&mut out, i, j);
			i = j;
		} else if ch == 'r' && raw_prefix && matches!(next, Some('"' | '#')) {
			// r"..." / r#"..."# (also br, cr); r#name is a raw identifier.
			let mut j = i + 1;
			let mut hashes = 0;
			while c.get(j) == Some(&'#') {
				hashes += 1;
				j += 1;
			}
			if c.get(j) != Some(&'"') {
				i = j;
				continue;
			}
			j += 1;
			while j < c.len() && !(c[j] == '"' && (0..hashes).all(|k| c.get(j + 1 + k) == Some(&'#'))) {
				j += 1;
			}
			let e = (j + 1 + hashes).min(c.len());
			blank(&mut out, i, e);
			i = e;
		} else if ch == '"' {
			let mut j = i + 1;
			while j < c.len() && c[j] != '"' {
				j += if c[j] == '\\' { 2 } else { 1 };
			}
			blank(&mut out, i, j + 1);
			i = j + 1;
		} else if ch == '\'' && next == Some('\\') {
			let mut j = i + 3;
			while j < c.len() && c[j] != '\'' && c[j] != '\n' {
				j += 1;
			}
			blank(&mut out, i, j + 1);
			i = j + 1;
		} else if ch == '\'' && c.get(i + 2) == Some(&'\'') {
			blank(&mut out, i, i + 3);
			i += 3;
		} else {
			// Code, a lifetime or a loop label.
			i += 1;
		}
	}
	out
}

/// The fns of a file (comments and literals blanked): name, first line, last line (1-based).
fn fns(code: &[char]) -> Vec<(String, usize, usize)> {
	let mut line_of = Vec::with_capacity(code.len());
	let mut ln = 1;
	for &ch in code {
		line_of.push(ln);
		if ch == '\n' {
			ln += 1;
		}
	}
	let mut out = Vec::new();
	let mut i = 0;
	while i + 2 < code.len() {
		if !(code[i] == 'f' && code[i + 1] == 'n' && (i == 0 || !ident(code[i - 1])) && code[i + 2].is_whitespace()) {
			i += 1;
			continue;
		}
		let mut j = i + 2;
		while j < code.len() && code[j].is_whitespace() {
			j += 1;
		}
		if code.get(j..j + 2) == Some(&['r', '#']) {
			j += 2;
		}
		let s = j;
		while j < code.len() && ident(code[j]) {
			j += 1;
		}
		if j == s {
			// `fn(..)` pointer type, or a macro's `fn $name`.
			i += 2;
			continue;
		}
		// The body's `{` outside () and [] (a `;` first: a declaration without a body).
		let mut depth = 0i32;
		let mut k = j;
		let open = loop {
			match code.get(k) {
				None => break None,
				Some('(' | '[') => depth += 1,
				Some(')' | ']') => depth -= 1,
				Some(';') if depth == 0 => break None,
				Some('{') if depth == 0 => break Some(k),
				_ => {}
			}
			k += 1;
		};
		if let Some(o) = open {
			let (mut d, mut e) = (0, o);
			while e < code.len() {
				match code[e] {
					'{' => d += 1,
					'}' => {
						d -= 1;
						if d == 0 {
							break;
						}
					}
					_ => {}
				}
				e += 1;
			}
			out.push((code[s..j].iter().collect(), line_of[i], line_of[e.min(code.len() - 1)]));
		}
		// Go on inside the signature and body: nested fns count on their own too.
		i = j;
	}
	out
}

#[derive(Default)]
struct Sizes {
	/// Hand-written file -> lines.
	files: BTreeMap<String, usize>,
	/// (file, fn name) -> lines of the longest fn of that name in that file.
	fns: BTreeMap<(String, String), usize>,
	/// The DIRS that exist here.
	scanned: Vec<&'static str>,
}

fn generated(text: &str) -> bool {
	text.lines().take(5).any(|l| {
		let l = l.to_ascii_lowercase();
		l.contains("generated by") || l.contains("@generated")
	})
}

fn walk(dir: &Path, root: &Path, s: &mut Sizes) {
	let Ok(rd) = std::fs::read_dir(dir) else { return };
	let mut paths: Vec<PathBuf> = rd.flatten().map(|e| e.path()).collect();
	paths.sort();
	for p in paths {
		if p.is_dir() {
			walk(&p, root, s);
			continue;
		}
		if p.extension().is_none_or(|x| x != "rs") {
			continue;
		}
		let Ok(bytes) = std::fs::read(&p) else { continue };
		let text = String::from_utf8_lossy(&bytes);
		if generated(&text) {
			continue;
		}
		let key = p.strip_prefix(root).unwrap_or(&p).to_string_lossy().replace('\\', "/");
		s.files.insert(key.clone(), text.lines().count());
		for (name, a, b) in fns(&code_only(&text)) {
			let n = s.fns.entry((key.clone(), name)).or_insert(0);
			*n = (*n).max(b + 1 - a);
		}
	}
}

fn measure() -> Sizes {
	let root = root();
	let mut s = Sizes::default();
	for d in DIRS {
		let p = root.join(d);
		if p.is_dir() {
			s.scanned.push(d);
			walk(&p, &root, &mut s);
		}
	}
	s
}

#[derive(Default)]
struct Caps {
	files: BTreeMap<String, usize>,
	fns: BTreeMap<(String, String), usize>,
}

fn read_caps() -> Option<Caps> {
	Some(parse_caps(&std::fs::read_to_string(caps_path()).ok()?))
}

/// SIZE_CAPS.txt as committed (git HEAD of the rac-rs repo); None outside a git checkout or before its first commit.
fn committed_caps() -> Option<Caps> {
	let out = std::process::Command::new("git").args(["-C", env!("CARGO_MANIFEST_DIR"), "show", "HEAD:SIZE_CAPS.txt"]).output().ok()?;
	out.status.success().then(|| parse_caps(&String::from_utf8_lossy(&out.stdout)))
}

/// SIZE_CAPS.txt: `file PATH LINES` and `fn PATH NAME LINES` lines; `#` lines are comments.
fn parse_caps(text: &str) -> Caps {
	let mut c = Caps::default();
	for l in text.lines() {
		let w: Vec<&str> = l.split_whitespace().collect();
		let num = |v: &str| v.parse::<usize>().unwrap_or_else(|_| panic!("SIZE_CAPS.txt: bad number in {l:?}"));
		match w.as_slice() {
			["file", p, n] => {
				c.files.insert(p.to_string(), num(n));
			}
			["fn", p, name, n] => {
				c.fns.insert((p.to_string(), name.to_string()), num(n));
			}
			[] => {}
			[first, ..] if first.starts_with('#') => {}
			_ => panic!("SIZE_CAPS.txt: cannot read {l:?}"),
		}
	}
	c
}

fn scanned(s: &Sizes, path: &str) -> bool {
	s.scanned.iter().any(|d| path.starts_with(&format!("{d}/")))
}

const HEADER: &str = "# Size caps of the hand-written files and fns that were over the limits on 2026-10-22 (file 1500 lines, fn 150 lines).
# Kept by rac-rs/src/size_limits_tests.rs: growing past a cap fails the unit tests; new big files or fns are not allowed.
# A cap only goes down: after shrinking one, run  RAC_SIZE_CAPS_WRITE=1 cargo test --lib size_limits  (lowers caps, drops the
# ones back within the limit). Never raise a cap or add a line by hand: split the file (ARCHITECTURE.md \"Where to change X\") or
# break the fn into named steps (scratch_perf_rf\\FUNC_RULES.md). A pure move of a capped item: change its path here by hand.
# Paths are relative to the project folder (rac-rs's parent).
";

fn write_caps(files: &BTreeMap<String, usize>, fns: &BTreeMap<(String, String), usize>) {
	let mut t = String::from(HEADER);
	for (p, n) in files {
		t += &format!("file {p} {n}\n");
	}
	for ((p, name), n) in fns {
		t += &format!("fn {p} {name} {n}\n");
	}
	let tmp = caps_path().with_extension("txt.tmp");
	std::fs::write(&tmp, t).expect("write SIZE_CAPS.txt.tmp");
	std::fs::rename(&tmp, caps_path()).expect("replace SIZE_CAPS.txt");
}

#[test]
fn no_file_or_fn_grows_past_its_limit() {
	let s = measure();
	let c = read_caps().unwrap_or_default();
	let mut bad = Vec::new();
	for (p, &n) in &s.files {
		let cap = c.files.get(p).copied().unwrap_or(FILE_MAX).max(FILE_MAX);
		if n > cap {
			bad.push(format!("file {p}: {n} lines, limit {cap}"));
		}
	}
	for ((p, name), &n) in &s.fns {
		let cap = c.fns.get(&(p.clone(), name.clone())).copied().unwrap_or(FN_MAX).max(FN_MAX);
		if n > cap {
			bad.push(format!("fn {name} in {p}: {n} lines, limit {cap}"));
		}
	}
	assert!(
		bad.is_empty(),
		"too big (split the file into modules by job, see ARCHITECTURE.md \"Where to change X\"; break a fn into named steps, see \
		 scratch_perf_rf\\FUNC_RULES.md; never raise a cap in SIZE_CAPS.txt):\n{}",
		bad.join("\n")
	);
}

#[test]
fn size_caps_are_tight() {
	let s = measure();
	let write = std::env::var("RAC_SIZE_CAPS_WRITE").is_ok_and(|v| v == "1");
	let Some(c) = read_caps() else {
		assert!(write, "SIZE_CAPS.txt is missing next to Cargo.toml");
		let files = s.files.iter().filter(|(_, n)| **n > FILE_MAX).map(|(p, &n)| (p.clone(), n)).collect();
		let fns = s.fns.iter().filter(|(_, n)| **n > FN_MAX).map(|(k, &n)| (k.clone(), n)).collect();
		write_caps(&files, &fns);
		return;
	};
	// Each cap against today's size: `None` = drop it (gone, or back within the limit), else the size to keep.
	let tight = |cap: usize, now: Option<usize>, max: usize| now.filter(|&n| n > max).map(|n| n.min(cap));
	let mut loose = Vec::new();
	let (mut files, mut fns) = (BTreeMap::new(), BTreeMap::new());
	for (p, &cap) in &c.files {
		if !scanned(&s, p) {
			files.insert(p.clone(), cap);
			continue;
		}
		let t = tight(cap, s.files.get(p).copied(), FILE_MAX);
		if t != Some(cap) {
			loose.push(format!("file {p}: cap {cap}, now {}", s.files.get(p).map_or("gone".into(), |n| n.to_string())));
		}
		if let Some(t) = t {
			files.insert(p.clone(), t);
		}
	}
	for ((p, name), &cap) in &c.fns {
		let k = (p.clone(), name.clone());
		if !scanned(&s, p) {
			fns.insert(k, cap);
			continue;
		}
		let t = tight(cap, s.fns.get(&k).copied(), FN_MAX);
		if t != Some(cap) {
			loose.push(format!("fn {name} in {p}: cap {cap}, now {}", s.fns.get(&k).map_or("gone".into(), |n| n.to_string())));
		}
		if let Some(t) = t {
			fns.insert(k, t);
		}
	}
	if write {
		write_caps(&files, &fns);
		return;
	}
	assert!(
		loose.is_empty(),
		"SIZE_CAPS.txt allows more than the code needs now; lower it with  RAC_SIZE_CAPS_WRITE=1 cargo test --lib size_limits  \
		 (a moved item: change its path in SIZE_CAPS.txt by hand):\n{}",
		loose.join("\n")
	);
}

/// Against the committed SIZE_CAPS.txt (a merge brings a lane's copy in before the dev commit): no cap went up and no item
/// was added. A moved item may take over the cap of a dropped one (fn: the same name; file: any dropped file) that is not lower.
#[test]
fn no_cap_was_raised_or_added() {
	let (Some(now), Some(was)) = (read_caps(), committed_caps()) else { return };
	let mut bad = Vec::new();
	let mut dropped_files: Vec<usize> = was.files.iter().filter(|(p, _)| !now.files.contains_key(*p)).map(|(_, &n)| n).collect();
	for (p, &n) in &now.files {
		match was.files.get(p) {
			Some(&w) if n > w => bad.push(format!("file {p}: cap raised from {w} to {n}")),
			Some(_) => {}
			None => match dropped_files.iter().position(|&w| w >= n) {
				Some(i) => {
					dropped_files.remove(i);
				}
				None => bad.push(format!("file {p}: cap {n} added")),
			},
		}
	}
	let mut dropped_fns: Vec<(&str, usize)> =
		was.fns.iter().filter(|(k, _)| !now.fns.contains_key(*k)).map(|((_, name), &n)| (name.as_str(), n)).collect();
	for ((p, name), &n) in &now.fns {
		match was.fns.get(&(p.clone(), name.clone())) {
			Some(&w) if n > w => bad.push(format!("fn {name} in {p}: cap raised from {w} to {n}")),
			Some(_) => {}
			None => match dropped_fns.iter().position(|&(m, w)| m == name && w >= n) {
				Some(i) => {
					dropped_fns.remove(i);
				}
				None => bad.push(format!("fn {name} in {p}: cap {n} added")),
			},
		}
	}
	assert!(
		bad.is_empty(),
		"SIZE_CAPS.txt may only go down: split the file or break up the fn instead (compared with git HEAD):\n{}",
		bad.join("\n")
	);
}

#[test]
fn the_scan_sees_the_source() {
	let s = measure();
	assert!(s.scanned.contains(&"rac-rs/src"));
	assert!(s.files.len() > 100 && s.fns.len() > 1000, "scan found {} files, {} fns", s.files.len(), s.fns.len());
}

#[test]
fn fn_lengths_skip_literals_and_comments() {
	let src = "fn a() {\n\tlet s = \"}\";\n\tlet c = '}';\n\t// }\n\t/* } /* } */ */\n\tlet r = r#\"}\"#;\n}\n\
		fn b<'x>(v: &'x [u8; 2]) -> u8 {\n\tfn inner() {}\n\tlet f: fn(u8) -> u8 = |x| x;\n\tv[0]\n}\n\
		trait T { fn decl(&self) -> [u8; 4]; }\nfn r#match() { let q = '\\''; let b = b'{'; }\n";
	let got = fns(&code_only(src));
	let want = [("a", 1, 7), ("b", 8, 12), ("inner", 9, 9), ("match", 14, 14)];
	let got: Vec<(&str, usize, usize)> = got.iter().map(|(n, a, b)| (n.as_str(), *a, *b)).collect();
	assert_eq!(got, want);
}
