	#[test]
	fn identities_are_sorted_and_unique() {
		let ids = super::METAL_TEXTURES;
		assert!(!ids.is_empty());
		assert!(ids.windows(2).all(|w| w[0].0 < w[1].0));
		let find = |id: u64| ids.binary_search_by_key(&id, |r| r.0);
		assert!(find(0xd049c79ef9c61bef).is_err(), "hero cloth must never get the metal effect");
		assert!(find(0xfa227899a42da9e5).is_ok(), "the wrench keeps its metal look");
	}
	#[test]
	fn kind_column_uses_every_kind_and_only_known_codes() {
		let ids = super::METAL_TEXTURES;
		assert!(ids.iter().all(|r| r.1 <= rac_engine::pack::METAL_PAINTED));
		for k in [super::P, super::M, super::B, super::D] { assert!(ids.iter().any(|r| r.1 == k), "kind {k} unused"); }
		// Most of the selection is plain polished metal; mirrors stay rare.
		assert!(ids.iter().filter(|r| r.1 == super::M).count() < ids.len() / 10);
	}
